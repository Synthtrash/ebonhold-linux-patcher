package ui

import (
	"fmt"
	"strings"
)

type translate func(string, ...any) string

func launcherText(language string) translate {
	return func(text string, args ...any) string {
		if language == "fr" {
			if translated, ok := frenchText[text]; ok {
				text = translated
			}
		}
		if len(args) > 0 {
			return fmt.Sprintf(text, args...)
		}
		return text
	}
}

// Translate the launcher-owned parts of a diagnostic without altering its raw cause.
func (tr translate) diagnostic(text string) string {
	if line, ok := strings.CutPrefix(text, "line "); ok {
		if number, reason, ok := strings.Cut(line, ": "); ok {
			if localized := tr(reason); localized != reason {
				return tr("line %s: %s", number, localized)
			}
		}
	}
	for _, prefix := range [...]string{"request download link: ", "renew sign-in: ", "HD patch backed up to "} {
		if reason, ok := strings.CutPrefix(text, prefix); ok {
			label, localized := tr(prefix), tr(reason)
			if label != prefix || localized != reason {
				return label + localized
			}
			return text
		}
	}
	return tr(text)
}

